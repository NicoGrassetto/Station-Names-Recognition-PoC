def normalize_phrase_list_language(language_or_locale: str) -> str:
    """Return the phrase-list language key for a language name or BCP-47 locale."""
    key = language_or_locale.strip().lower().replace("_", "-")
    try:
        return _LANGUAGE_ALIASES[key]
    except KeyError as exc:
        supported = ", ".join(sorted(_LANGUAGE_ALIASES))
        raise ValueError(
            f"Unsupported phrase-list language {language_or_locale!r}. Supported: {supported}"
        ) from exc


def get_phrase_list(language_or_locale: str) -> list[str]:
    """Return a copy of the station phrase list for a language or locale."""
    language = normalize_phrase_list_language(language_or_locale)
    return list(_PHRASE_LISTS_BY_LANGUAGE[language])


def get_phrase_lists_by_language() -> dict[str, list[str]]:
    """Return copies of all station phrase lists keyed by iRail language code."""
    return {
        language: list(phrases)
        for language, phrases in _PHRASE_LISTS_BY_LANGUAGE.items()
    }


